import json
import re

from app.schemas import ConversationRequest, ProposalRequest

PROJECT_HINTS = (
    "need", "build", "website", "app", "design", "fix", "project",
    "budget", "deadline", "milestone", "deliver", "develop", "create",
)


class FakeProvider:
    """Deterministic provider for tests and LLM_PROVIDER=fake."""

    def generate(self, prompt: str, *, system: str = "", json_schema: dict | None = None) -> str:
        # Inputs unused for determinism; real providers use them.
        _ = (prompt, system, json_schema)
        payload = {
            "proposal": (
                "Hi — I can help with this project based on the requirements you shared. "
                "I would focus on the core deliverables first, keep communication clear, "
                "and share progress checkpoints. What is your preferred start date?"
            ),
            "suggested_price": {
                "amount": 350,
                "currency": "USD",
                "rationale": "Estimate from typical scope for this job type (fake provider).",
            },
            "delivery_days": 7,
            "questions_to_ask": ["What is your preferred start date?"],
            "warnings": ["Generated by FakeProvider — not a real LLM."],
        }
        return json.dumps(payload)

    def generate_from_request(self, request: ProposalRequest) -> str:
        skills = ", ".join(request.profile.skills[:3]) or "your skills"
        detail = request.job.title[:80]
        payload = {
            "proposal": (
                f"Hi — regarding “{detail}”, I can help using {skills}. "
                "I read the requirements carefully and would start by clarifying scope, "
                "confirming acceptance criteria, then deliver a clean first version with "
                "short notes so you can review quickly. I keep communication clear and "
                "share progress checkpoints. What is the must-have for the first milestone?"
            ),
            "suggested_price": {
                "amount": float(request.profile.hourly_rate or 40) * 8,
                "currency": request.profile.currency,
                "rationale": (
                    f"Anchored to budget “{request.job.budget_text}”."
                    if request.job.budget_text
                    else "Estimate from hourly rate × assumed scope (fake provider)."
                ),
            },
            "delivery_days": 7 if request.options.length == "short" else 10,
            "questions_to_ask": ["What is the must-have for the first milestone?"],
            "warnings": ["Generated by FakeProvider — not a real LLM."],
        }
        return json.dumps(payload)

    def analyze_from_request(self, request: ConversationRequest) -> str:
        """Keyword heuristic so tests and local runs need no LLM."""
        client_text = " ".join(m.text for m in request.messages if m.role == "client")
        lowered = client_text.lower()
        hits = [w for w in PROJECT_HINTS if re.search(rf"\b{w}\b", lowered)]
        if len(hits) < 2:
            payload = {
                "has_project": False,
                "title": "",
                "summary": "",
                "requirements": [],
                "budget_text": None,
                "deadline": None,
                "reason": "The client has not described any work yet (fake provider).",
            }
        else:
            sentences = re.split(r"(?<=[.!?])\s+", client_text.strip())
            first = next(
                (s for s in sentences if any(re.search(rf"\b{w}\b", s.lower()) for w in hits)),
                "",
            )[:80]
            budget = re.search(r"\$\s?\d[\d,.]*\d|\$\s?\d", client_text)
            payload = {
                "has_project": True,
                "title": first or "Project from conversation",
                "summary": client_text[:400],
                "requirements": [],
                "budget_text": budget.group(0) if budget else None,
                "deadline": None,
                "reason": f"Client mentions: {', '.join(hits[:4])} (fake provider).",
            }
        return json.dumps(payload)

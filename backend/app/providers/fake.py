import json

from app.schemas import ProposalRequest


class FakeProvider:
    """Deterministic provider for tests and LLM_PROVIDER=fake."""

    def generate(self, prompt: str, *, system: str = "") -> str:
        # Prompt/system unused for determinism; real providers use them in Phase 4.
        _ = (prompt, system)
        payload = {
            "proposal": (
                "Hi — I can help with this project based on the requirements you shared. "
                "I would focus on the core deliverables first, keep communication clear, "
                "and share progress checkpoints. What is your preferred start date?"
            ),
            "suggested_price": {
                "amount": 350,
                "currency": "USD",
                "rationale": "Estimate from typical scope for this job type (fake provider).",
            },
            "delivery_days": 7,
            "questions_to_ask": ["What is your preferred start date?"],
            "warnings": ["Generated by FakeProvider — not a real LLM."],
        }
        return json.dumps(payload)

    def generate_from_request(self, request: ProposalRequest) -> str:
        skills = ", ".join(request.profile.skills[:3]) or "your skills"
        detail = request.job.title[:80]
        payload = {
            "proposal": (
                f"Hi — regarding “{detail}”, I can help using {skills}. "
                "I read the requirements carefully and would start by clarifying scope, "
                "confirming acceptance criteria, then deliver a clean first version with "
                "short notes so you can review quickly. I keep communication clear and "
                "share progress checkpoints. What is the must-have for the first milestone?"
            ),
            "suggested_price": {
                "amount": float(request.profile.hourly_rate or 40) * 8,
                "currency": request.profile.currency,
                "rationale": (
                    f"Anchored to budget “{request.job.budget_text}”."
                    if request.job.budget_text
                    else "Estimate from hourly rate × assumed scope (fake provider)."
                ),
            },
            "delivery_days": 7 if request.options.length == "short" else 10,
            "questions_to_ask": ["What is the must-have for the first milestone?"],
            "warnings": ["Generated by FakeProvider — not a real LLM."],
        }
        return json.dumps(payload)
